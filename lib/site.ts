import type { Metadata } from "next";

export const siteName = "SalesMoni";
export const siteDescription =
  "Record every sale, keep your stock up to date, and download Excel reports for any period.";

/**
 * The public address of the site. Social networks need full URLs for preview
 * images, so set NEXT_PUBLIC_SITE_URL to your live domain when you deploy.
 */
export const siteUrl =
  process.env.NEXT_PUBLIC_SITE_URL ??
  (process.env.VERCEL_PROJECT_PRODUCTION_URL
    ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
    : "http://localhost:3000");

/** The shared preview image, generated by app/opengraph-image.tsx. */
const previewImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: "SalesMoni: know what you sold, what's left, and what you made.",
};

interface PageMetadataInput {
  /** Shown in the browser tab and as the headline of a shared link. */
  title: string;
  description?: string;
  /** The page's path, e.g. "/auth/login". */
  path: string;
}

/** Title, description, and social preview tags for one page. */
export function pageMetadata({ title, description = siteDescription, path }: PageMetadataInput): Metadata {
  const fullTitle = `${title} · ${siteName}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName,
      title: fullTitle,
      description,
      url: path,
      locale: "en_NG",
      images: [previewImage],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [previewImage],
    },
  };
}
